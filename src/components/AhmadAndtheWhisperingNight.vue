            <p>   Deep in the green, rolling hills, where the grass is soft and the clouds are like fluffy pillows, lived a little boy named Ahmad. Ahmad, who was just five years old, had a very special routine.

Every evening, after his parents tucked him in and read him a funny story, and after the last star twinkled to life, Ahmad would slip out of his cozy bed and into his quiet backyard. He had a secret place there, a little platform he’d made, right under the biggest, most magical tree. Ahmad wasn't trying to cause trouble; he just loved the night.

Tonight was extra special. A huge, friendly crescent moon was smiling down, looking like a silver banana. The air smelled of jasmine, and the ground felt cool under his feet. He unrolled his little green prayer mat, the one with the golden tassels, right there on the grass.

Ahmad put on his clean, white thobe and hisfavorite matching cap. Then, he set up his little wooden book stand and placed his open copy of the Quran upon it. The words in the book always made his heart feel warm, even if he was still learning to read them.

He lit his beautiful, glass lantern, and its golden light danced, casting safe and happy shadows. A string of prayer beads lay beside the book, waiting.

Ahmad knelt down, just like he had learned, and made his first dua. He thanked the moon for being so bright and the stars for their twinkling. He asked for his parents to have good dreams and for all the creatures in the hills to be warm and safe.

But then, the quiet got a little too quiet. A small, strange, scritch-scratchy noise came from behind a bush. And then a tiny whisper.

Ahmad’s heart did a little jump-scare. The friendly night started to feel a little bigger, and the shadows from the tree trunks looked a bit less safe. He looked up at the moon, and then back at the bush.

Slowly, Ahmad reached for his prayer beads. He didn't want to run away. He remembered his favorite dua for courage. He took a deep breath, and holding a single, warm bead in his fingers, he closed his eyes and started to softly recite.

“Allahumma, help me be brave... Allahumma, keep me safe...”

When he opened his eyes again, the scritch-scratchy noise stopped. The lantern seemed even brighter, and the stars looked even more playful. He was still just a little boy in a big garden, but he felt different.

From behind the bush, a tiny pair of glowing eyes peeking out. A very small, very shy field mouse hobbled forward, looking hungry.

Ahmad smiled, a small but brave smile. He reached into his pocket and pulled out a tiny piece of the date his mother had given him. He set it on the ground near the mouse.

Ahmad returned to his prayers. This time, he added a special thought for the small field mouse.

“And Allahumma, please make sure the little mouse gets a big, delicious crumb tonight.”

The moon smiled down even bigger, and the night didn’t feel scary at all anymore. Ahmad finished his dua, blew out his lantern, and, feeling warmer and braver than ever before, knew he had made the night just a little bit more magical.</p>
                    
