                            A shepherd told his youngest son to tend the flock of sheep,<br>

                            “The wolf will try to chase them, if he catches you asleep!”<br>



                            The boy sat down beside a tree, and did as he was told.<br>

                            By noon, the job of watching sheep was getting rather old.<br>



                            They didn’t like his jokes, and wouldn’t let him ride their backs,<br>

                            They only cared for eating grass and daffodils for snacks.<br>



                            And then he had a great idea, a trick that he could play,<br>

                            So brilliant and so simple, it would save his boring day!<br>



                            “Wolf! The Wolf!” he cried aloud, “He’s hiding in a tree!”<br>

                            You’ve got to come and help, before he makes a meal of me!”<br>



                            The villagers came running when they heard the scary news.<br>

                            The sight they found atop the hill left all of them confused.<br>



                            The boy was not in danger and the wolf was not in sight.<br>

                            It was clear the quiet, napping sheep were perfectly alright.<br>



                            “I tricked you!” said the boy, as people went back down the hill.<br>

                            When each of them returned to work, the boy was laughing still.<br>



                            About an hour later, he was sick of lazy sheep.<br>

                            He tried to start a choir, but they wouldn’t make a peep.<br>



                            He had no choice, but once again, to play a clever trick.<br>

                            He thought of something new to yell, convinced that he was slick.<br>



                            “Wolf! The Wolf!” he cried aloud, “He’s got an air balloon!”<br>

                            “He’ll grab the sheep and all their wool unless you save them soon.”<br>



                            The townsfolk hadn’t any clue that wolves knew how to fly,<br>

                            But if it had an air attack, they’d like to see it try.<br>



                            Again the boy was laughing when they came upon the hill.<br>

                            And some declared, “We won’t come back!” It seemed they had their fill.<br>



                            All day long the boy kept on, and kept himself amused.<br>

                            And each time fewer people came, to find that they’d been rused.<br>



                            “Wolf! The Wolf” he cried aloud, “he’s come by submarine!”<br>

                            “Wolf! The Wolf! He’s in a bush, and painted forest green!”<br>



                            “He’s dug from underground. This time he has a robot army!”<br>

                            “He’s got me, and he says to bring some cookies or he’ll harm me!”<br>



                            By dusk a single woman came, and no one else was there.<br>

                            She vowed to never come again. The boy said, “I don’t care.”<br>



                            He took a bite of cookie and laid down to get some rest.<br>

                            “No one tells such funny lies. It’s clear that I’m the best.”<br>



                            But then from down below he saw the wolf approach his herd.<br>

                            It captured seven sheep before he even said a word.<br>



                            “Wolf! The wolf!” he cried aloud, “He’s here to take the flock!”<br>

                            But all he got were yells that said, “Pipe down! It’s six o’clock!”<br>



                            By night the wolf was full. It’d eaten every single one.<br>

                            The shepherd came and scared him off and found his youngest son.<br>



